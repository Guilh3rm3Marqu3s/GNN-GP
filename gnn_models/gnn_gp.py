import torch
import torch.nn.functional as F
from torch.nn import ModuleList, Dropout, ReLU, Linear
from torch_geometric.nn import MessagePassing
from torch_geometric.utils import add_remaining_self_loops, degree, softmax

# ======================================
#               GCN
# ======================================
class GP_GCNConv(MessagePassing):
    """
    Custom GCN Layer that accepts a custom aggregation function
    """
    def __init__(self, in_channels, out_channels, aggr_func=None):
        # 'flow' defines the direction of message propagation (source_to_target is standard)
        # aggr=None because we will handle aggregation manually in the aggregate() method
        super().__init__(aggr=None, flow='source_to_target') 
        
        self.in_channels = in_channels
        self.out_channels = out_channels
        self.aggr_func = aggr_func  # The function generated by DEAP
        
        # standard linear transformation (Theta)
        self.lin = Linear(in_channels, out_channels, bias=False)
        self.bias = torch.nn.Parameter(torch.Tensor(out_channels))

        self.reset_parameters()

    def reset_parameters(self):
        self.lin.reset_parameters()
        self.bias.data.zero_()

    def forward(self, x, edge_index):
        # add self-loops to the adjacency matrix (Standard GCN procedure)
        edge_index, _ = add_remaining_self_loops(edge_index, num_nodes=x.size(0))

        # linear Transformation
        x = self.lin(x)

        # compute Normalization (Node degrees)
        row, col = edge_index
        deg = degree(col, x.size(0), dtype=x.dtype)
        deg_inv_sqrt = deg.pow(-0.5)
        deg_inv_sqrt[deg_inv_sqrt == float('inf')] = 0
        norm = deg_inv_sqrt[row] * deg_inv_sqrt[col]

        # 4. Propagate messages
        # This calls message() and then aggregate() internally
        out = self.propagate(edge_index, x=x, norm=norm)

        # 5. Add bias
        out = out + self.bias

        return out

    def message(self, x_j, norm):
        """
        Constructs messages to node i from each neighbor j.
        x_j: Features of neighbors [num_edges, out_channels]
        norm: Normalization coefficients [num_edges]
        """
        return norm.view(-1, 1) * x_j

    def aggregate(self, inputs, index, ptr=None, dim_size=None):
        """
        Replaces the standard aggregation ('add', 'mean') with the GP function.
        
        Args:
            inputs: Tensor of messages from neighbors [num_edges, out_channels]
            index: Indices of target nodes [num_edges]
            dim_size: Total number of nodes (used for scatter dimensions)
        """
        if self.aggr_func is not None:
            
            if dim_size is None:
                dim_size = int(index.max()) + 1
            
            # arguments for GP Tree signature
            zeros = inputs.new_zeros((dim_size, inputs.size(1)))
            
            
            return self.aggr_func(inputs, index, dim_size,zeros)
            
            
        else:
            raise Exception('A custom aggregation function must be passed.')


class GCN_GP(torch.nn.Module):
    """
    GCN Model that builds the architecture using the custom GP_GCNConv layer.
    """
    def __init__(self, in_channels, hidden_channels, out_channels, num_layers, aggr_func, dropout_rate=0.5):
        super().__init__()
        self.dropout_rate = dropout_rate
        self.aggr_func = aggr_func # Function generated by DEAP
        
        self.layers = ModuleList()
        
        if num_layers == 1:
            # Single layer
            self.layers.append(GP_GCNConv(in_channels, out_channels, aggr_func=self.aggr_func))
        else:
            # Input layer
            self.layers.append(GP_GCNConv(in_channels, hidden_channels, aggr_func=self.aggr_func))
            
            # Hidden layers
            for _ in range(num_layers - 2):
                self.layers.append(GP_GCNConv(hidden_channels, hidden_channels, aggr_func=self.aggr_func))
                
            # Output layer
            self.layers.append(GP_GCNConv(hidden_channels, out_channels, aggr_func=self.aggr_func))
            
        self.relu = ReLU()
        self.dropout = Dropout(p=self.dropout_rate)
        
    def forward(self, data):
        x, edge_index = data.x, data.edge_index
        
        # Iterate over all layers except the last one
        for layer in self.layers[:-1]:
            x = layer(x, edge_index)
            x = self.relu(x)
            x = self.dropout(x)
            
        # Last layer (No ReLU/Dropout before softmax in standard GCN)
        x = self.layers[-1](x, edge_index)
        
        return F.log_softmax(x, dim=1)
    


