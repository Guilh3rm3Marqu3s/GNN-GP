class GP_GINConv(MessagePassing):
    """
    Custom GIN Layer with GP Aggregation.
    
    Logic:
    1. Aggregate neighbors using GP (replacing standard Sum).
    2. Add self-loop with a learnable epsilon: (1 + eps) * x_i.
    3. Pass the result through an MLP.
    """
    def __init__(self, mlp, aggr_func=None, train_eps=True):
        
        super().__init__(aggr=None, flow='source_to_target')
        
        self.mlp = mlp
        self.aggr_func = aggr_func
        
        # learnable epsilon parameter
        if train_eps:
            self.eps = torch.nn.Parameter(torch.Tensor([0.0]))
        else:
            self.register_buffer('eps', torch.Tensor([0.0]))

    def forward(self, x, edge_index):
        # propagate (aggregate neighbors via GP)
        # Note: GIN typically doesn't add self-loops to edge_index because it handles the central node x separately via (1+eps).
        out_neigh = self.propagate(edge_index, x=x)

        # combine with Self
        out = out_neigh + (1 + self.eps) * x

        # apply MLP
        return self.mlp(out)

    def message(self, x_j):
        return x_j

    def aggregate(self, inputs, index, ptr=None, dim_size=None):
        if self.aggr_func is not None:
            if dim_size is None:
                dim_size = int(index.max()) + 1
            
            # arguments for GP Tree signature
            zeros = inputs.new_zeros((dim_size, inputs.size(1)))
            return self.aggr_func(inputs, index, dim_size, zeros)
        else:
            raise Exception('GP_GINConv: No custom aggregation function passed.')


class GIN_GP(torch.nn.Module):
    def __init__(self, in_channels, hidden_channels, out_channels, num_layers, aggr_func, dropout_rate=0.5):
        super().__init__()
        self.dropout_rate = dropout_rate
        self.aggr_func = aggr_func
        self.layers = ModuleList()
        
        # helper to create MLP
        def make_mlp(input_dim, output_dim):
            return torch.nn.Sequential(
                torch.nn.Linear(input_dim, output_dim),
                torch.nn.ReLU(inplace=False), # Important: inplace=False
                torch.nn.Linear(output_dim, output_dim)
            )

        if num_layers == 1:
             self.layers.append(GP_GINConv(make_mlp(in_channels, out_channels), aggr_func=self.aggr_func))
        else:
            # input
            self.layers.append(GP_GINConv(make_mlp(in_channels, hidden_channels), aggr_func=self.aggr_func))
            # hidden
            for _ in range(num_layers - 2):
                self.layers.append(GP_GINConv(make_mlp(hidden_channels, hidden_channels), aggr_func=self.aggr_func))
            # output
            self.layers.append(GP_GINConv(make_mlp(hidden_channels, out_channels), aggr_func=self.aggr_func))
            
        self.dropout = Dropout(p=self.dropout_rate, inplace=False)
        
    def forward(self, data):
        x, edge_index = data.x, data.edge_index
        for layer in self.layers[:-1]:
            x = layer(x, edge_index)
            x = F.relu(x)
            x = self.dropout(x)
        x = self.layers[-1](x, edge_index)
        return F.log_softmax(x, dim=1)