class GP_SAGEConv(MessagePassing):
    """
    Custom GraphSAGE Layer that uses the GP function to aggregate neighbors.
    Logic: Output = Linear_Self(Node) + Linear_Neigh( Aggr_GP(Neighbors) )
    """
    
    def __init__(self, in_channels, out_channels, aggr_func=None):
        
        super().__init__(aggr=None, flow='source_to_target')
        
        self.in_channels = in_channels
        self.out_channels = out_channels
        self.aggr_func = aggr_func
        
        # GraphSAGE uses two distinct linear weights:
        # 1: transform the features of the node itself (root)
        self.lin_r = Linear(in_channels, out_channels, bias=False)
        # 2:  transform the aggregated features of the neighbors
        self.lin_l = Linear(in_channels, out_channels, bias=True) # Bias is usually here

        self.reset_parameters()
        
    def reset_parameters(self):
        self.lin_r.reset_parameters()
        self.lin_l.reset_parameters()
        
    def forward(self, x, edge_index):
        # linear transformation of self (Root Node)
        # x = [Num_Nodes, In_Channels]
        out_self = self.lin_r(x)

        # propagation (neighbor aggregation via GP)
        out_neigh = self.propagate(edge_index, x=x)
        
        # linear transformation of aggregated neighbors
        out_neigh = self.lin_l(out_neigh)

        # combination
        
        return out_self + out_neigh
    
    
    def message(self, x_j):
        """
        In SAGE, the message is just the raw neighbor feature.
        The GP will decide if it applies ReLU, Identity, etc., before aggregating.
        """
        return x_j
    
    def aggregate(self, inputs, index, ptr=None, dim_size=None):
        """
        inputs: Neighbor features (x_j)
        index: Target indices
        """
        if self.aggr_func is not None:
            # detect feature dimension            
            if dim_size is None:
                dim_size = int(index.max()) + 1

            # arguments for GP Tree signature
            zeros = inputs.new_zeros((dim_size, inputs.size(1)))
            
            # call the evolved function passing all 4 arguments
            return self.aggr_func(inputs, index, dim_size, zeros)
        else:
            raise Exception('GP_SAGEConv: No custom aggregation function passed.')
        
        
class SAGE_GP(torch.nn.Module):
    """
    SAGE Model architecture that builds the network using the custom GP_SAGEConv layer.
    """
    def __init__(self, in_channels, hidden_channels, out_channels, num_layers, aggr_func, dropout_rate=0.5):
        super().__init__()
        self.dropout_rate = dropout_rate
